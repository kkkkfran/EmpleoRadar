def normalize_text_match(text: str) -> str:
    """Normaliza texto para comparaciones sin tildes ni mayúsculas."""
    import unicodedata

    n = unicodedata.normalize("NFD", text.strip().lower())
    return "".join(c for c in n if unicodedata.category(c) != "Mn")


# Index para búsquedas rápidas: comuna normalizada -> (nombre_oficial, region)
_COMUNA_LOOKUP: dict[str, tuple[str, str]] = {}
for region, comunas in REGIONES_CHILE.items():
    for comuna in comunas:
        _COMUNA_LOOKUP[normalize_text_match(comuna)] = (comuna, region)

# Variantes comunes de escritura
_SYNONYMS: dict[str, tuple[str, str]] = {
    "chillan": ("Chillán", "Ñuble"),
    "chillan viejo": ("Chillán Viejo", "Ñuble"),
    "san carlos": ("San Carlos", "Ñuble"),
    "nuble": ("Chillán", "Ñuble"),
    "region de nuble": ("Chillán", "Ñuble"),
    "region del nuble": ("Chillán", "Ñuble"),
    "stgo": ("Santiago", "Metropolitana de Santiago"),
    "santiago centro": ("Santiago", "Metropolitana de Santiago"),
    "region metropolitana": ("Santiago", "Metropolitana de Santiago"),
    "rm": ("Santiago", "Metropolitana de Santiago"),
}


def find_comuna_and_region(text: str) -> tuple[str | None, str | None]:
    """Identifica la comuna y región de Chile a partir de un texto de ubicación."""
    if not text:
        return None, None

    normalized = normalize_text_match(text)

    # Revisar sinónimos directos ordenados por longitud descendente
    for syn, (c_name, r_name) in sorted(_SYNONYMS.items(), key=lambda x: len(x[0]), reverse=True):
        if syn == normalized or syn in normalized.split(",") or f" {syn} " in f" {normalized} ":
            return c_name, r_name

    # Buscar coincidencia exacta o por subcadenas ordenadas por longitud descendente
    for norm_c, (c_name, r_name) in sorted(
        _COMUNA_LOOKUP.items(), key=lambda x: len(x[0]), reverse=True
    ):
        # Coincidencia con palabras delimitadas
        if (
            norm_c == normalized
            or f" {norm_c} " in f" {normalized} "
            or f",{norm_c}" in normalized
            or f"{norm_c}," in normalized
        ):
            return c_name, r_name

    # Buscar coincidencia por nombre de región
    for region in REGIONES_CHILE:
        norm_r = normalize_text_match(region)
        if norm_r in normalized:
            # Retornar región encontrada sin comuna específica
            return None, region

    return None, None
